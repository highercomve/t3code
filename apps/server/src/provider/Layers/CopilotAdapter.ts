/**
 * CopilotAdapter — GitHub Copilot CLI (`copilot --acp`) via ACP.
 *
 * Modeled on `CursorAdapter`. Copilot exposes a first-class ACP server
 * (verified against `copilot` v1.0.54: `--acp Start as Agent Client Protocol
 * server`). The session loop is identical in shape to Cursor — `initialize`
 * + `authenticate` + `session/new`|`session/load` + streaming
 * `session/update` notifications routed through `AcpSessionRuntime`.
 *
 * Copilot-specific spawn details:
 *   - `--acp`                    : run as ACP JSON-RPC server (stdio)
 *   - `--add-dir <cwd>`          : grant file-access scope to the session cwd
 *   - `--allow-all-tools`        : gated on `dangerouslySkipPermissions === true`
 *                                  (mirrors the Antigravity escape hatch)
 * Auth method id: `copilot-login` (probed from `initialize` `authMethods[]`).
 *
 * Model selection is honored via the ACP `model` config option after the
 * session is created, the same mechanism Cursor uses — the CLI accepts a
 * `--model` flag too, but routing through ACP keeps mid-session model
 * switches in scope without requiring a respawn.
 *
 * @module provider/Layers/CopilotAdapter
 */

